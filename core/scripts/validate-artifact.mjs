// Тело раздела: от заголовка до следующего «## ». Нужно там, где требование
// адресовано КОНКРЕТНОМУ разделу: «где-то в файле есть ID теста» — не то же
// самое, что «этот кейс попал в таблицу автотестов».
//
// html-комментарии шаблона вырезаем: это инструкция агенту, а не содержимое
// артефакта, и удалять её из готового файла нигде не предписано. Иначе
// проверка засчитывала бы СВОЮ ЖЕ подсказку за ответ — раздел с одним
// комментарием шаблона проходил бы как заполненный.
function sectionBody(text, heading) {
  const start = text.indexOf(heading);
  if (start === -1) return '';
  const rest = text.slice(start + heading.length);
  const end = rest.search(/\n## /);
  return (end === -1 ? rest : rest.slice(0, end)).replace(/<!--[\s\S]*?-->/g, '');
}

// Идентификатор теста в Jira (аннотация `@TmsLink`): ключ проекта, `T` и
// номер — `PROJ-T113`. У нового теста в TMS ещё нет номера, и план пишет
// плейсхолдер со сквозным суффиксом `-1`, `-2`: без него все новые тесты
// получили бы ОДИН ID, состав ID схлопнулся бы и потерянный тест не поймался
// бы сверкой отчёта с планом.
//
// Ключ задачи (`PROJ-198`) и требование (`REQ-1`) под шаблон не попадают —
// в них нет `T` перед номером, и это единственное, что отличает ID теста от
// прочих ID в том же файле.
const TMS_ID = /\b[A-Z][A-Z0-9]{1,14}-T\d+(?:-\d+)?\b/g;
// Тот же шаблон, но на ВСЮ строку и без /g: им проверяется ячейка ID, где
// посторонний текст рядом с идентификатором — ошибка, а не совпадение.
const TMS_CELL = /^[A-Z][A-Z0-9]{1,14}-T\d+(?:-\d+)?$/;

// Список ID тестов в прозе, без повторов. Только там, где ID вкраплён в текст
// (раздел «Что не автоматизируем»); у таблиц ID берётся из ячейки.
function ids(text) {
  return [...new Set(text.match(TMS_ID) || [])];
}

// Разбор markdown-таблицы в теле раздела. ID берётся ИЗ ПЕРВОЙ ЯЧЕЙКИ строки,
// а не поиском по тексту раздела: иначе идентификатор, упомянутый в прозе
// («переиспользуется, как в PROJ-T100», обоснование регресса под таблицей),
// считался бы за строку таблицы. Такой «фантом» стоит дорого в обе стороны:
// сверка отчёта с планом требует несуществующий тест, а кейс без автотеста
// проходит проверку покрытия по одному упоминанию в соседней строке.
function tableLines(body) {
  return body.split('\n').filter((l) => /^\s*\|/.test(l) && !/^[\s|:-]+$/.test(l));
}

function cells(line) {
  // Делим по `|`, КРОМЕ экранированного `\|`: шаблон предписывает писать
  // вертикальную черту в ячейке именно так, и разбор обязан считать её
  // текстом. Иначе правильно оформленная строка падала бы на проверке числа
  // ячеек — с советом сделать ровно то, что уже сделано.
  const parts = line.trim().split(/(?<!\\)\|/);
  if (parts[0] === '') parts.shift();
  if (parts.length && parts[parts.length - 1] === '') parts.pop();
  return parts.map((c) => c.trim());
}

// Шапка таблицы — первая непустая строка с `|`; остальные строки — данные.
function tableHead(body) {
  const t = tableLines(body);
  return t.length ? cells(t[0]) : [];
}

function tableRows(body) {
  return tableLines(body).slice(1).map(cells);
}

// ID строк таблицы В ПОРЯДКЕ ПОЯВЛЕНИЯ И С ПОВТОРАМИ: дедупликация здесь
// скрыла бы ровно то, что проверяется отдельным правилом, — два теста с
// одним ID.
function rowIds(body) {
  return tableRows(body).map((r) => r[0] || '');
}

// Заполнена ли колонка `name` у каждой строки. Колонки нет в шапке — про это
// говорит отдельное правило о составе колонок, здесь молчим.
function filled(body, names) {
  const head = tableHead(body);
  const idx = names.map((n) => head.indexOf(n)).filter((i) => i >= 0);
  return tableRows(body).every((r) => idx.every((i) => (r[i] || '') !== ''));
}

// ID кейсов, названных в «Что не автоматизируем». Считаем ТОЛЬКО то, что
// стоит после «Кейсы:» — как предписывает шаблон: ID, случайно попавший в
// текст причины, покрытием не является.
function skippedIds(body) {
  const out = [];
  for (const line of body.split('\n')) {
    const m = line.match(/Кейсы:\s*(.+)$/);
    if (m) out.push(...(m[1].match(TMS_ID) || []));
  }
  return out;
}

